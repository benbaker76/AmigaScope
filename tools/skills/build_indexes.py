def function_table(sk, lib, patterns, base=None):
    """Markdown table of every function in the TSV with LVO, registers and its entry link."""
    base = base or os.path.join(SKILLS, sk, 'reference')
    where = {}
    for pat in patterns:
        for f in sorted(glob.glob(os.path.join(SKILLS, sk, 'reference', pat))):
            for lvl, h, a, s in entries(f):
                if lvl == 2: where.setdefault(h, (os.path.relpath(f, base).replace(os.sep, '/') + '#' + a, s))
    tsv = os.path.join(SKILLS, sk, 'reference', 'data', f'{lib}.tsv')
    rows = ['| Function | LVO | Registers | Summary |', '|---|---|---|---|']
    for r in sorted(read_tsv(tsv), key=lambda r: r['function'].lower()):
        link, s = where.get(r['function'], ('', ''))
        name = f"[{r['function']}]({link})" if link else r['function']
        alias = f" (alias: {r['aliases'].replace(',', ', ')})" if r['aliases'] else ''
        rows.append(f"| {name}{alias} | {r['lvo']} | {r['registers']} | {s} |")
    return rows

def build_os():
    sk = 'amiga-os'
    libs = OS_LIBS + ['audio']                         # audio.device: commands only, no LVO table
    for lib in libs:
        p = os.path.join(SKILLS, sk, 'reference', lib, 'index.md')
        if not os.path.exists(p): continue
        text = open(p, encoding='utf-8').read()
        if '<!-- FUNCTION TABLE -->' not in text or not os.path.exists(os.path.join(SKILLS, sk, 'reference', 'data', f'{lib}.tsv')):
            continue
        head = text.split('<!-- FUNCTION TABLE -->')[0].rstrip() + '\n\n'
        tbl = function_table(sk, lib, [f'{lib}/*.md'], base=os.path.join(SKILLS, sk, 'reference', lib))
        write(p, head + '<!-- FUNCTION TABLE -->\n' + GENERATED + '\n## Functions\n\n' + '\n'.join(tbl) +
              f'\n\nMachine-readable: [../data/{lib}.tsv](../data/{lib}.tsv)\n')
    out = [GENERATED, '# amiga-os reference index', '',
           'Every public function of exec, dos, graphics, intuition, diskfont, utility, layers and',
           'lowlevel, the timer/input device functions and the cia/potgo resources (AmigaOS 3.9',
           'NDK), with LVO and register assignments generated from the NDK SFD files, plus the',
           'timer, input and audio device commands.', '',
           '- [Sources](SOURCE.md) · [Errata](errata.md)', '',
           '## Guides', ''] + guide_list(sk, 'topics/*.md') + ['', '## Libraries', '']
    for lib in libs:
        p = os.path.join(SKILLS, sk, 'reference', lib, 'index.md')
        if os.path.exists(p):
            t, s = title_and_summary(p)
            out.append(f'- [{t}]({lib}/index.md)' + (f' — {s}' if s else ''))
            out += ['  ' + l for l in guide_list(sk, f'{lib}/*.md')]
    cmds = entry_list(sk, ['timer/commands.md', 'input/commands.md', 'audio/commands.md'],
                      label=lambda f: os.path.basename(os.path.dirname(f)) + '.device')
    if cmds:
        out += ['', '## Device commands', ''] + cmds
    out += ['', '## All functions (alphabetical)', '']
    items = []
    for lib in libs:
        tsv = os.path.join(SKILLS, sk, 'reference', 'data', f'{lib}.tsv')
        if not os.path.exists(tsv): continue
        where = {}
        for f in glob.glob(os.path.join(SKILLS, sk, 'reference', lib, '*.md')):
            for lvl, h, a, s in entries(f):
                if lvl == 2: where.setdefault(h, (rel(sk, f) + '#' + a, s))
        for r in read_tsv(tsv):
            link, s = where.get(r['function'], ('', ''))
            items.append((r['function'], lib, r['lvo'], link, s))
    for n, lib, lvo, link, s in sorted(items, key=lambda x: x[0].lower()):
        out.append(f'- `{n}` ({lib} {lvo})' + (f' — {s}' if s else '') + (f' → [{link.split("#")[0]}]({link})' if link else ''))
    write(os.path.join(SKILLS, sk, 'reference', 'index.md'), '\n'.join(out) + '\n')

if __name__ == '__main__':
    for fn in (build_hardware, build_aga, build_asm, build_ahi, build_os):
        fn()
