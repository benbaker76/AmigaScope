#!/usr/bin/env python3
"""Build the generated indexes of the Amiga agent skills.

  build_indexes.py            rewrite every reference/index.md (and the function tables
                              appended to amiga-os/reference/<lib>/index.md)

Summaries come from each entry's first prose line (the one-sentence summary rule), so
re-run this after editing entries. Hand-written intros live in INTRO below or, for the
per-library amiga-os indexes, above their `<!-- FUNCTION TABLE -->` marker.
"""
import glob, os, re, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SKILLS = os.path.join(REPO, '.agents', 'skills')
sys.path.insert(0, os.path.dirname(__file__))
from amiga_skill_data import slug, read_tsv, code_blanked, OS_LIBS  # noqa: E402

GENERATED = '<!-- Generated by tools/skills/build_indexes.py - do not edit by hand. -->\n'

def entries(path):
    """[(level, heading, anchor, summary)] for the ## and # headings of a file."""
    lines = open(path, encoding='utf-8').read().split('\n')
    blank = code_blanked('\n'.join(lines))
    out, seen = [], {}
    for i, line in enumerate(blank):
        m = re.match(r'^(#{1,2})\s+(.*?)\s*$', line)
        if not m: continue
        s = slug(m.group(2)); n = seen.get(s, 0); seen[s] = n + 1
        summary = ''
        for nxt in lines[i + 1:i + 12]:
            t = nxt.strip()
            if not t or t.startswith('`') or t.startswith('Registers:') or t.startswith('<!--'): continue
            if ' · ' in t and '`$' in t: continue          # register fact line not starting with the address
            if t.startswith(('#', '|', '```', '- ', '* ', '>')): break
            para = []
            for more in lines[lines.index(nxt, i + 1):]:
                if not more.strip() or more.lstrip().startswith(('#', '|', '```', '- ', '* ')): break
                para.append(more.strip())
            text = ' '.join(para)
            m2 = re.match(r'(.+?[.])(\s|$)', text)
            summary = m2.group(1) if m2 else text
            summary = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', summary)   # links are relative to the entry file
            if len(summary) > 180: summary = summary[:177].rsplit(' ', 1)[0] + '...'
            break
        out.append((len(m.group(1)), m.group(2), f'{s}-{n}' if n else s, summary))
    return out

def rel(skill, path):
    return os.path.relpath(path, os.path.join(SKILLS, skill, 'reference')).replace(os.sep, '/')

def title_and_summary(path):
    es = entries(path)
    top = next((e for e in es if e[0] == 1), None)
    return (top[1], top[3]) if top else (os.path.basename(path), '')

def guide_list(skill, pattern):
    lines = []
    for f in sorted(glob.glob(os.path.join(SKILLS, skill, 'reference', pattern))):
        if os.path.basename(f) == 'index.md': continue
        t, s = title_and_summary(f)
        lines.append(f'- [{t}]({rel(skill, f)})' + (f' — {s}' if s else ''))
    return lines

def entry_list(skill, patterns, label=None):
    items = []
    for pat in patterns:
        for f in sorted(glob.glob(os.path.join(SKILLS, skill, 'reference', pat))):
            if os.path.basename(f) == 'index.md': continue
            for lvl, h, a, s in entries(f):
                if lvl != 2: continue
                items.append((h, f'{rel(skill, f)}#{a}', s, label(f) if label else ''))
    items.sort(key=lambda x: (x[0].lower(), x[3]))
    return [f'- `{h}`' + (f' ({lab})' if lab else '') + (f' — {s}' if s else '') + f' → [{p.split("#")[0]}]({p})'
            for h, p, s, lab in items]

def write(path, text):
    with open(path, 'w', encoding='utf-8', newline='\n') as o: o.write(text)
    print('wrote', os.path.relpath(path, REPO))

# ------------------------------------------------------------------ registers by address
REG_TSV = os.path.join(SKILLS, 'amiga-hardware', 'reference', 'data', 'registers.tsv')
REG_COLS = ['address', 'name', 'width', 'ndk_label', 'chipset', 'access', 'description', 'entry']

def register_heads(skill):
    """[(regex, heading-name, link, fact tokens, summary)] for the register entries of a skill."""
    heads = []
    for f in sorted(glob.glob(os.path.join(SKILLS, skill, 'reference', 'registers', '*.md'))):
        lines = open(f, encoding='utf-8').read().split('\n')
        for lvl, h, a, s in entries(f):
            if lvl != 2: continue
            i = lines.index('## ' + h)
            fact = next((l for l in lines[i + 1:i + 4] if ' · ' in l), '')
            toks = [t.strip() for t in fact.split(' · ')]
            toks = [t for t in toks if not re.match(r'^(CIA-[AB] )?`\$', t)]   # drop address tokens -> [access, chip, chipset, ...]
            toks = ['addr'] + toks
            for n in re.split(r',|/', h):
                n = n.strip()
                if not n: continue
                pat = re.escape(n).replace('xx', r'\d\d').replace('x', r'[0-9A-D]')
                heads.append((re.compile('^' + pat + '$'), n, rel(skill, f) + '#' + a, toks, s))
    return heads

def find_head(heads, row, exact):
    name, addr = {'POTINP': 'POTGOR'}.get(row['name'], row['name']), row['address']
    if addr.startswith('$BF'):
        chip = 'CIAA' if addr.startswith('$BFE') else 'CIAB'
        hit = next((h for h in heads if h[1] == f'{chip} {name}'), None)
        if hit: return hit
    base = re.sub(r'(PT|LC)$', r'\1H', name) if row['width'] == 'L' else name   # 32-bit names -> xxxH entry
    if exact:
        return next((h for h in heads if h[1] in (name, base)), None)
    return next((h for h in heads if h[0].match(name) or h[0].match(base)), None)

def refresh_registers():
    """Fill chipset/access/description/entry of registers.tsv from the written entries."""
    hw, aga = register_heads('amiga-hardware'), register_heads('amiga-aga')
    rows = read_tsv(REG_TSV)
    for r in rows:
        src = next(((k, h) for exact in (True, False) for k, hs in (('hw', hw), ('aga', aga))
                    for h in [find_head(hs, r, exact)] if h), (None, None))
        k, h = src
        if k == 'hw':
            toks = h[3]
            r['chipset'] = next((c for c in ('OCS', 'ECS', 'AGA') if any(re.search(r'\b' + c + r'\b', t) for t in toks[2:])), '')
            r['access'] = toks[1] if len(toks) > 1 else ''
            r['description'], r['entry'] = h[4], 'amiga-hardware:' + h[2]
        elif k == 'aga':
            if h:
                r['chipset'], r['access'] = 'AGA', h[3][1] if len(h[3]) > 1 else ''
                r['description'], r['entry'] = h[4], 'amiga-aga:' + h[2]
    with open(REG_TSV, 'w', encoding='utf-8', newline='\n') as o:
        o.write('\t'.join(REG_COLS) + '\n')
        for r in rows: o.write('\t'.join(r.get(c, '').replace('\t', ' ') for c in REG_COLS) + '\n')
    missing = [r['name'] for r in rows if not r['entry']]
    print(f'registers.tsv: {len(rows)} rows, {len(missing)} without an entry: {" ".join(missing)}')
    return rows

# ------------------------------------------------------------------ skills
def build_hardware():
    sk = 'amiga-hardware'
    rows = refresh_registers()
    out = [GENERATED, '# amiga-hardware reference index', '',
           'OCS/ECS custom chips (Agnus, Denise, Paula) and the two 8520 CIAs, distilled from the',
           'Amiga Hardware Reference Manual and checked against the NDK 3.9 hardware includes.',
           'AGA-only registers are in the amiga-aga skill.', '',
           '- [Sources](SOURCE.md) · [Errata](errata.md) · [Register table (TSV)](data/registers.tsv)', '',
           '## Guides', ''] + guide_list(sk, 'topics/*.md') + [
           '', '## Register files', ''] + guide_list(sk, 'registers/*.md') + [
           '', '## Registers by address', '',
           'Width L rows are the 32-bit names of H/L pointer pairs (one `move.l` from the CPU).', '',
           '| Address | Register | Width | Chipset | Access | Description |', '|---|---|---|---|---|---|']
    for r in rows:
        skill, _, link = r['entry'].partition(':')
        name = f"[{r['name']}]({link})" if skill == sk else r['name']
        desc = r['description'] if skill == sk else (r['description'] + ' (see the amiga-aga skill)').strip()
        out.append(f"| `{r['address']}` | {name} | {r['width']} | {r['chipset']} | {r['access']} | {desc} |")
    out += ['', '## Register entries (alphabetical)', ''] + entry_list(sk, ['registers/*.md'])
    write(os.path.join(SKILLS, sk, 'reference', 'index.md'), '\n'.join(out) + '\n')

def build_aga():
    sk = 'amiga-aga'
    regs = sorted(glob.glob(os.path.join(SKILLS, sk, 'reference', 'registers', '*.md')))
    out = [GENERATED, '# amiga-aga reference index', '',
           'AGA (AA chipset: Alice, Lisa, Paula) registers and techniques for the A1200, A4000 and',
           'CD32. OCS/ECS behaviour of the same registers is in the amiga-hardware skill.', '',
           '- [Sources](SOURCE.md) · [Errata](errata.md)', '',
           '## Guides', ''] + guide_list(sk, 'topics/*.md') + [
           '', '## Register entries', ''] + entry_list(sk, ['registers/*.md'])
    aga = register_heads(sk)
    out += ['', '## Registers by address', '', 'Registers with an AGA-specific entry here; every other register is in the amiga-hardware skill.', '',
            '| Address | Register | Entry |', '|---|---|---|']
    for r in read_tsv(REG_TSV):
        h = find_head(aga, r, True) or find_head(aga, r, False)
        if h: out.append(f"| `{r['address']}` | [{r['name']}]({h[2]}) | {h[4]} |")
    write(os.path.join(SKILLS, sk, 'reference', 'index.md'), '\n'.join(out) + '\n')

